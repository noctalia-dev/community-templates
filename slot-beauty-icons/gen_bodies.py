#!/usr/bin/env python3
"""Precompute, for every recolourable icon, the colour that covers the most
visible area -- the folder's "face".

Frequency of hex strings in the source is a poor proxy: a small badge can be
written many times while the face is a single path.  Rendering each icon once
and classifying pixels against the icon's own palette gives the real answer.

The result is static (independent of the target colour), so it is written to a
TSV and shipped with the template.  Regenerate it only if the icon pack
changes:

    python3 gen_bodies.py "$HOME/.local/share/icons/Slot-Beauty-Dark-Icons-V-2/places" bodies.tsv
"""
import colorsys
import os
import re
import subprocess
import sys
import tempfile

import recolor as R

SIZES = ("8", "16", "22", "24", "32", "48", "64", "96")
MAX_DIST2 = 0.02          # a pixel must be close to a palette entry to count
ALPHA_MIN = 160


def palette(text):
    stripped = R.NAMEDVIEW.sub("", text)
    freq = {}
    for c in R.HEX.findall(stripped):
        c = c.lower()
        if c not in R.PURE:
            freq[c] = freq.get(c, 0) + 1
    return freq


def render(path, size):
    fd, png = tempfile.mkstemp(suffix=".png")
    os.close(fd)
    try:
        subprocess.run(
            ["rsvg-convert", "-w", str(size), "-h", str(size), path, "-o", png],
            check=True, capture_output=True,
        )
        from PIL import Image
        with Image.open(png) as im:
            return im.convert("RGBA").copy()
    finally:
        os.unlink(png)


def area_body(path, text):
    freq = palette(text)
    sat = [c for c in freq if colorsys.rgb_to_hls(*R.h2r(c))[2] >= R.NEUTRAL_SAT]
    if not sat:
        return None

    img = render(path, 64)
    pals = [(c, R.h2r(c)) for c in sat]
    count = {c: 0 for c in sat}
    px = img.load()
    for y in range(img.height):
        for x in range(img.width):
            r, g, b, a = px[x, y]
            if a < ALPHA_MIN:
                continue
            r, g, b = r / 255.0, g / 255.0, b / 255.0
            best, best_d = None, MAX_DIST2
            for c, (pr, pg, pb) in pals:
                d = (r - pr) ** 2 + (g - pg) ** 2 + (b - pb) ** 2
                if d < best_d:
                    best, best_d = c, d
            if best is not None:
                count[best] += 1

    if not any(count.values()):
        return None
    return max(count, key=count.get)


