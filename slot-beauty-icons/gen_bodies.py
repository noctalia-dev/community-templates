# table entry always corresponds to a file recolor.py will actually rewrite.
def is_folder_icon(name):
    if not name.endswith(".svg") or "symbolic" in name:
        return False
    return name.startswith("folder") or name in ("user-desktop.svg", "user-home.svg")


def main():
    places = sys.argv[1]
    out = sys.argv[2]
    rows = []
    for size in SIZES:
        d = os.path.join(places, size)
        if not os.path.isdir(d):
            continue
        for name in sorted(os.listdir(d)):
            if not is_folder_icon(name):
                continue
            path = os.path.join(d, name)
            if os.path.islink(path) or not os.path.isfile(path):
                continue
            with open(path, encoding="utf-8", errors="replace") as fh:
                text = fh.read()
            body = area_body(path, text)
            if body:
                rows.append("%s/%s\t%s" % (size, name, body))
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(rows) + "\n")
    print("%d bodies -> %s" % (len(rows), out))
# End of AI-generated section.


if __name__ == "__main__":
    main()
