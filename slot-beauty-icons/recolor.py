#!/usr/bin/env python3
"""Recolour Slot Beauty folder SVGs so the folder body lands on a target colour.

Algorithm (body-anchored):

  * The icon's "body" is its most-visible saturated colour (the folder face).
    It is precomputed once per icon into ``bodies.tsv``; when no body is known
    it falls back to the most frequent saturated colour.
  * The body maps exactly onto the target (hue, saturation, lightness).
  * Every other saturated colour keeps its original lightness *offset* from the
    body and its saturation ratio, so gradients, back-tabs and badges keep
    their relative tonal structure.
  * Light neutrals (glyph lines such as #eff0f1) stay light so the glyphs stay
    legible; dark neutrals (shadows, bases) stay dark with a faint tint.
  * Icons with no saturated colour at all are left untouched.
"""
# This section has been AI-generated by Gemini 3.8 Flash (High) on 25.11.2026
import colorsys
import os
import re
import sys
import tempfile
import time

PURE = {"#000000", "#ffffff"}
NEUTRAL_SAT = 0.15      # below this a colour carries no hue identity
GLYPH_L = 0.55          # neutrals at/above this are glyph lines, not shadows

BODY_MIN_SAT = 0.25     # a folder face is clearly saturated...
BODY_MIN_L = 0.32       # ...and clearly lighter than the dark base plate
MAX_DELTA = 0.35        # cap how far a shade may travel from its origin

# The namedview block is editor metadata (page colour, border colour, ...).
# It must not influence body detection; its hex values are still rewritten
# harmlessly so the substitution stays single-pass.
NAMEDVIEW = re.compile(
    r"<sodipodi:namedview\b[^>]*/>|<sodipodi:namedview\b.*?</sodipodi:namedview>",
    re.S,
)
HEX = re.compile(r"#[0-9a-fA-F]{6}")


def h2r(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def r2h(r, g, b):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))


def clamp(v, lo=0.0, hi=1.0):
    return max(lo, min(hi, v))


def pick_body(freq, info):
    """The folder face: frequent, clearly saturated, not the dark base plate."""
    for min_sat, min_l in ((BODY_MIN_SAT, BODY_MIN_L), (0.20, 0.25), (NEUTRAL_SAT, 0.0)):
        cands = [c for c in freq if info[c][2] >= min_sat and info[c][1] >= min_l]
        if cands:
            return max(cands, key=lambda c: (freq[c] * info[c][2], info[c][1]))
    return None


def build_mapping(freq, target, body=None):
    th, tl, ts = colorsys.rgb_to_hls(*h2r(target))
    info = {c: colorsys.rgb_to_hls(*h2r(c)) for c in freq}

    # A shipped body table may not match the installed pack version; fall back
    # to detecting the body from the file itself rather than skipping the icon.
    if body is None or body not in info:
        body = pick_body(freq, info)
    if body is None:
        return {}

    _, bl, bs = info[body]
    bs = max(bs, 0.05)

    mapping = {}
    for c, (h, l, s) in info.items():
        if s >= NEUTRAL_SAT:
            delta = max(-MAX_DELTA, min(MAX_DELTA, l - bl))
            nl = clamp(tl + delta, 0.08, 0.95)
            ns = clamp(ts * (s / bs))
            r, g, b = colorsys.hls_to_rgb(th, nl, ns)
        elif l >= GLYPH_L:
            # glyph line: keep it bright, give it a whisper of the target hue
            r, g, b = colorsys.hls_to_rgb(th, l, min(s, 0.05))
        else:
            # shadow / base / outline: keep it dark
            r, g, b = colorsys.hls_to_rgb(th, clamp(l, 0.0, 0.30), min(s, 0.10))
        mapping[c] = r2h(r, g, b)
    return mapping


def recolor(text, target, body=None):
    """Return ``(new_text, mapping, changed)``."""
    stripped = NAMEDVIEW.sub("", text)

    freq = {}
    for c in HEX.findall(stripped):
        c = c.lower()
        if c not in PURE:
            freq[c] = freq.get(c, 0) + 1

    mapping = build_mapping(freq, target, body) if freq else {}
    if not mapping:
        return text, {}, False

    changed = False

    def sub(m):
        nonlocal changed
        src = m.group(0)
        new = mapping.get(src.lower())
        if new is None or new == src.lower():
            return src
        changed = True
        return new

    return HEX.sub(sub, text), mapping, changed


def atomic_write(target_path, content, mode=0o644):
    """Write content to target_path atomically using a securely created temporary file.
    Creates the temporary file in the same directory and replaces target_path atomically.
    """
    target_path = os.path.abspath(target_path)
    dirname = os.path.dirname(target_path)
    os.makedirs(dirname, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=dirname, prefix=".tmp-", delete=False, encoding="utf-8", newline="") as tf:
        tmp_name = tf.name
        tf.write(content)
    try:
        os.chmod(tmp_name, mode)
        os.replace(tmp_name, target_path)
    except Exception:
        if os.path.exists(tmp_name):
            try:
                os.unlink(tmp_name)
            except OSError:
                pass
        raise


def recolor_file(path, target, body=None, dry_run=False):
    """Recolour one file in place atomically. Returns ``changed`` | ``same`` | ``error:<msg>``."""
    if os.path.islink(path):
        return "error: cannot recolour symlink directly"
    try:
        # newline="" keeps the original line endings byte for byte.
        with open(path, encoding="utf-8", errors="replace", newline="") as fh:
            text = fh.read()
    except OSError as exc:
        return "error:%s" % exc

    new, _, changed = recolor(text, target, body)
    if not changed:
        return "same"
    if dry_run:
        return "changed"

    atomic_write(path, new)
    return "changed"


def load_bodies(path):
    """Read the ``<size>/<file>\\t#rrggbb`` body table."""
    bodies = {}
    if not path or not os.path.isfile(path):
        return bodies
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line or line.startswith("#") or "\t" not in line:
                continue
            key, val = line.split("\t", 1)
            bodies[key] = val.strip().lower()
    return bodies


def make_symlink(src_path, dst_path, src_root, dst_root):
    """Create or update a symlink pointing to the corresponding file or rewritten path."""
    if not os.path.islink(src_path):
        target = os.path.realpath(src_path)
    else:
        link = os.readlink(src_path)
        if link.startswith("/"):
            resolved = os.path.realpath(src_path)
            if resolved.startswith(src_root + "/"):
                target = os.path.join(dst_root, resolved[len(src_root) + 1:])
            else:
                target = resolved
        else:
            target = link

    if os.path.islink(dst_path):
        if os.readlink(dst_path) != target:
            os.unlink(dst_path)
            os.symlink(target, dst_path)
    elif os.path.lexists(dst_path):
        if not os.path.isdir(dst_path):
            os.unlink(dst_path)
            os.symlink(target, dst_path)
    else:
        os.symlink(target, dst_path)


def sync_theme(src, dest, target, bodies_path=None):
    """Fast, atomic theme synchronization and folder recoloring.

    Never deletes active directories in-place, eliminating desktop icon fallback/flashing.
    Recolors all folder SVGs atomically using securely created temporary files and os.replace.
    """
    target = target.lstrip("#").lower()
    os.makedirs(dest, exist_ok=True)
    theme_name = "Slot-Beauty-Dark-Icons-V-2-Noctalia"
    base_theme = os.path.basename(os.path.abspath(src))

    # 1. index.theme
    index_dst = os.path.join(dest, "index.theme")
    needs_index = True
    if os.path.isfile(index_dst):
        try:
            with open(index_dst, "r", encoding="utf-8") as fh:
                existing_idx = fh.read()
            if theme_name in existing_idx and base_theme in existing_idx:
                needs_index = False
        except OSError:
            pass

    if needs_index:
        index_src = os.path.join(src, "index.theme")
        if os.path.exists(index_src):
            with open(index_src, "r", encoding="utf-8") as fh:
                idx_content = fh.read()
            idx_content = re.sub(
                r"^Name(\[[^]]*\])?=.*",
                rf"Name\1={theme_name}",
                idx_content,
                flags=re.MULTILINE,
            )
            if base_theme not in idx_content and re.search(r"^Inherits=", idx_content, flags=re.MULTILINE):
                idx_content = re.sub(
                    r"^Inherits=(.*)",
                    rf"Inherits={base_theme},\1",
                    idx_content,
                    flags=re.MULTILINE,
                )
            atomic_write(index_dst, idx_content)

    # 2. Top-level symlinks
    for entry in os.listdir(src):
        if entry in ("places", "index.theme", ".icon-theme.cache") or entry.startswith("."):
            continue
        dest_entry = os.path.join(dest, entry)
        make_symlink(os.path.join(src, entry), dest_entry, src, dest)

    # 3. places directory structure and non-folder symlinks
    src_places = os.path.join(src, "places")
    dst_places = os.path.join(dest, "places")
    os.makedirs(dst_places, exist_ok=True)

    bodies = load_bodies(bodies_path) if bodies_path else {}
    recolor_items = []

    for sname in sorted(os.listdir(src_places)):
        sdir = os.path.join(src_places, sname)
        ddir = os.path.join(dst_places, sname)

        if os.path.islink(sdir):
            target_link = os.readlink(sdir)
            if os.path.islink(ddir):
                if os.readlink(ddir) != target_link:
                    os.unlink(ddir)
                    os.symlink(target_link, ddir)
            elif not os.path.lexists(ddir):
                os.symlink(target_link, ddir)
            continue
        if not os.path.isdir(sdir):
            continue

        os.makedirs(ddir, exist_ok=True)

        for fname in os.listdir(sdir):
            fsrc = os.path.join(sdir, fname)
            fdst = os.path.join(ddir, fname)

            # Never treat symlinks as files to recolour; replicate the symlink instead
            if os.path.islink(fsrc):
                make_symlink(fsrc, fdst, src, dest)
                continue

            # Folder SVGs include regular folder*.svg and user-desktop.svg / user-home.svg
            is_folder_svg = (
                sname != "symbolic"
                and "symbolic" not in fname
                and (fname.startswith("folder") or fname in ("user-desktop.svg", "user-home.svg"))
                and fname.endswith(".svg")
                and os.path.isfile(fsrc)
            )

            if not is_folder_svg:
                make_symlink(fsrc, fdst, src, dest)
            else:
                # If fdst was previously a symlink, unlink it so atomic replace writes a real file
                if os.path.islink(fdst):
                    try:
                        os.unlink(fdst)
                    except OSError:
                        pass
                recolor_items.append((fsrc, fdst, f"{sname}/{fname}"))

    # 4. Atomic recoloring of all folder SVGs
    for fsrc, fdst, key in recolor_items:
        with open(fsrc, "r", encoding="utf-8", errors="replace", newline="") as fh:
            text = fh.read()
        body_val = bodies.get(key) or bodies.get(key.replace("user-", "folder-"))
        new_text, _, _ = recolor(text, target, body_val)
        atomic_write(fdst, new_text)

    # 5. Write target color stamp atomically
    stamp = os.path.join(dest, ".noctalia-color")
    atomic_write(stamp, target + "\n")

    # 6. Touch directory timestamps to notify inotify / mtime watchers
    now = time.time()
    try:
        os.utime(dst_places, (now, now))
        os.utime(dest, (now, now))
    except OSError:
        pass


if __name__ == "__main__":
    args = [a for a in sys.argv[1:]]
    bodies_path = None
    if "--bodies" in args:
        i = args.index("--bodies")
        bodies_path = args[i + 1]
        del args[i:i + 2]

    if args and args[0] == "sync":
        # python3 recolor.py sync <target> <src> <dest> [--bodies bodies.tsv]
        target, src, dest = args[1], args[2], args[3]
        sync_theme(src, dest, target, bodies_path)
    else:
        # Legacy CLI mode:
        # python3 recolor.py <target> <srcdir> <outdir> [--bodies bodies.tsv] [names...]
        bodies = load_bodies(bodies_path) if bodies_path else {}
        target, srcdir, outdir = args[0], args[1], args[2]
        size = os.path.basename(os.path.normpath(srcdir))
        os.makedirs(outdir, exist_ok=True)

        for name in args[3:]:
            if name.startswith("--"):
                continue
            if not name.endswith(".svg"):
                name += ".svg"
            p = os.path.join(srcdir, name)
            if os.path.islink(p) or not os.path.isfile(p):
                continue
            with open(p, encoding="utf-8", errors="replace", newline="") as fh:
                text = fh.read()
            body_val = bodies.get("%s/%s" % (size, name)) or bodies.get(("%s/%s" % (size, name)).replace("user-", "folder-"))
            new, _, changed = recolor(text, target, body_val)
            atomic_write(os.path.join(outdir, name), new)
