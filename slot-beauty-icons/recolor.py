# Reworked by DeepSeek V4.1 Flash Free on 25.11.2026: the module is now a pure
# sync function (apply.sh owns the freshness stamp) and prunes stale entries.
# Hardened by DeepSeek V4.1 Flash Free on 27.11.2026: destination symlinks are
# replaced before a directory is created, so a write cannot follow one out of
