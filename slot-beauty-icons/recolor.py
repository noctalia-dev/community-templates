import argparse
import colorsys
import os
import re
import shutil
import sys
import tempfile
import time

PURE = {"#000000", "#ffffff"}
NEUTRAL_SAT = 0.15      # below this a colour carries no hue identity
GLYPH_L = 0.55          # neutrals at/above this are glyph lines, not shadows

BODY_MIN_SAT = 0.25     # a folder face is clearly saturated...
BODY_MIN_L = 0.32       # ...and clearly lighter than the dark base plate
MAX_DELTA = 0.35        # cap how far a shade may travel from its origin

# The namedview block is editor metadata (page colour, border colour, ...).
# It must not influence body detection; its hex values are still rewritten
# harmlessly so the substitution stays single-pass.
NAMEDVIEW = re.compile(
    r"<sodipodi:namedview\b[^>]*/>|<sodipodi:namedview\b.*?</sodipodi:namedview>",
    re.S,
)
HEX = re.compile(r"#[0-9a-fA-F]{6}")


def h2r(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def r2h(r, g, b):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v * 255))) for v in (r, g, b))


def clamp(v, lo=0.0, hi=1.0):
    return max(lo, min(hi, v))


def pick_body(freq, info):
    """The folder face: frequent, clearly saturated, not the dark base plate."""
    for min_sat, min_l in ((BODY_MIN_SAT, BODY_MIN_L), (0.20, 0.25), (NEUTRAL_SAT, 0.0)):
        cands = [c for c in freq if info[c][2] >= min_sat and info[c][1] >= min_l]
        if cands:
            return max(cands, key=lambda c: (freq[c] * info[c][2], info[c][1]))
    return None


def build_mapping(freq, target, body=None):
    th, tl, ts = colorsys.rgb_to_hls(*h2r(target))
    info = {c: colorsys.rgb_to_hls(*h2r(c)) for c in freq}

    # A shipped body table may not match the installed pack version; fall back
    # to detecting the body from the file itself rather than skipping the icon.
    if body is None or body not in info:
        body = pick_body(freq, info)
    if body is None:
        return {}

    _, bl, bs = info[body]
    bs = max(bs, 0.05)

    mapping = {}
    for c, (h, l, s) in info.items():
        if s >= NEUTRAL_SAT:
            delta = max(-MAX_DELTA, min(MAX_DELTA, l - bl))
            nl = clamp(tl + delta, 0.08, 0.95)
            ns = clamp(ts * (s / bs))
            r, g, b = colorsys.hls_to_rgb(th, nl, ns)
        elif l >= GLYPH_L:
            # glyph line: keep it bright, give it a whisper of the target hue
            r, g, b = colorsys.hls_to_rgb(th, l, min(s, 0.05))
        else:
            # shadow / base / outline: keep it dark
            r, g, b = colorsys.hls_to_rgb(th, clamp(l, 0.0, 0.30), min(s, 0.10))
        mapping[c] = r2h(r, g, b)
    return mapping


def recolor(text, target, body=None):
    """Return the recoloured SVG text.

    The text is returned unchanged when no colour maps (an icon with no
    saturated colour at all), so callers can simply write the result.
    """
    stripped = NAMEDVIEW.sub("", text)

    freq = {}
    for c in HEX.findall(stripped):
        c = c.lower()
        if c not in PURE:
            freq[c] = freq.get(c, 0) + 1

    mapping = build_mapping(freq, target, body) if freq else {}
    if not mapping:
        return text

    return HEX.sub(lambda m: mapping.get(m.group(0).lower(), m.group(0)), text)


def atomic_write(path, content):
    """Write ``content`` to ``path`` through a secure temp file and a rename.

    The temp file lives in the destination directory so ``os.replace`` stays on
    one filesystem and the desktop never sees a half-written SVG.
    """
    path = os.path.abspath(path)
    directory = os.path.dirname(path)
    os.makedirs(directory, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        "w", dir=directory, prefix=".tmp-", delete=False, encoding="utf-8", newline=""
    ) as handle:
        tmp_name = handle.name
        handle.write(content)
    try:
        os.chmod(tmp_name, 0o644)
        os.replace(tmp_name, path)
    except Exception:
        if os.path.exists(tmp_name):
            try:
                os.unlink(tmp_name)
            except OSError:
                pass
        raise


def ensure_dir(path):
    """Create ``path`` as a real directory, replacing a symlink in the way.

    A size can change upstream from a symlink to a real directory.  The derived
    theme then still holds the old symlink, and creating or writing through it
    would land in the original pack (or in another size of the derived theme).
    Removing the link first keeps every write inside ``dest``.
    """
    if os.path.islink(path):
        os.unlink(path)
    os.makedirs(path, exist_ok=True)


def load_bodies(path):
    """Read the ``<size>/<file>\\t#rrggbb`` body table."""
    bodies = {}
    if not path:
        return bodies
    if not os.path.isfile(path):
        print(
            f"recolor.py: body table not found at {path}; detecting each body from its SVG",
            file=sys.stderr,
        )
        return bodies
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if not line or line.startswith("#") or "\t" not in line:
                continue
            key, val = line.split("\t", 1)
            bodies[key] = val.strip().lower()
    return bodies


def make_symlink(src_path, dst_path, src_root, dst_root):
    """Create or update a symlink pointing to the corresponding file or rewritten path."""
    if not os.path.islink(src_path):
        target = os.path.realpath(src_path)
    else:
        link = os.readlink(src_path)
        if link.startswith("/"):
            resolved = os.path.realpath(src_path)
            if resolved.startswith(src_root + "/"):
                target = os.path.join(dst_root, resolved[len(src_root) + 1:])
            else:
                target = resolved
        else:
            target = link

    if os.path.islink(dst_path):
        if os.readlink(dst_path) != target:
            os.unlink(dst_path)
            os.symlink(target, dst_path)
    elif os.path.lexists(dst_path):
        if not os.path.isdir(dst_path):
            os.unlink(dst_path)
            os.symlink(target, dst_path)
    else:
        os.symlink(target, dst_path)


def ensure_inherits(text, base_theme):
    """Prepend ``base_theme`` to the theme's Inherits list, once.

    ``Inherits`` is comma separated.  The previous check searched the whole
    file for the base name, which already matched ``Name=Slot-Beauty-Dark-Icons-V-2``
    and so never actually added the parent theme.
    """
    match = re.search(r"^Inherits=(.*)$", text, flags=re.MULTILINE)
    if not match:
        if re.search(r"^\[Icon Theme\]", text, flags=re.MULTILINE):
            return re.sub(
                r"^\[Icon Theme\]",
                f"[Icon Theme]\nInherits={base_theme}",
                text,
                count=1,
                flags=re.MULTILINE,
            )
        return text + f"\nInherits={base_theme}\n"
    parents = [p.strip() for p in match.group(1).split(",") if p.strip()]
    if base_theme in parents:
        return text
    parents.insert(0, base_theme)
    return text[: match.start(1)] + ",".join(parents) + text[match.end(1):]


def prune_stale(dest, expected):
    """Delete entries the source pack no longer ships.

    The walk is bottom-up so a directory can be removed once its contents are
    gone.  ``os.walk`` lists symlinked directories in ``dirs`` without
    descending into them, so those are treated as files.
    """
    keep = {".noctalia-color", ".icon-theme.cache"}
    removed = 0
    for root, dirs, files in os.walk(dest, topdown=False):
        rel_root = os.path.relpath(root, dest)
        rel_root = "" if rel_root == "." else rel_root
        entries = list(files) + [d for d in dirs if os.path.islink(os.path.join(root, d))]
        for name in entries:
            rel = os.path.join(rel_root, name) if rel_root else name
            if rel in expected or name in keep or name.startswith(".noctalia-color.tmp"):
                continue
            try:
                os.unlink(os.path.join(root, name))
                removed += 1
            except OSError:
                pass
        if rel_root and rel_root not in expected:
            try:
                os.rmdir(root)
            except OSError:
                pass
    return removed


def sync_theme(src, dest, target, bodies_path=None):
    """Build or refresh the derived theme and recolour its folder icons.

    The source pack is only read.  Everything under ``dest`` is either a
    symlink into the pack or a recoloured copy of a folder SVG, and entries the
    pack no longer ships are pruned so a pack update cannot leave stale icons
    behind.
    """
    target = target.lstrip("#").lower()
    if not re.fullmatch(r"[0-9a-f]{6}", target):
        raise SystemExit(f"recolor.py: not a six-digit hex colour: {target!r}")

    os.makedirs(os.path.dirname(os.path.abspath(dest)) or ".", exist_ok=True)
    ensure_dir(dest)
    theme_name = os.path.basename(os.path.abspath(dest))
    base_theme = os.path.basename(os.path.abspath(src))
    expected = {"index.theme"}

    # 1. index.theme.  Regenerating it is cheap and removes a whole class of
    # "the cached header went stale" bugs.
    index_src = os.path.join(src, "index.theme")
    if os.path.exists(index_src):
        with open(index_src, "r", encoding="utf-8") as fh:
            index = fh.read()
        index = re.sub(
            r"^Name(\[[^]]*\])?=.*",
            rf"Name\1={theme_name}",
            index,
            flags=re.MULTILINE,
        )
        atomic_write(os.path.join(dest, "index.theme"), ensure_inherits(index, base_theme))
    else:
        print(f"recolor.py: no index.theme in {src}", file=sys.stderr)

    # 2. Top-level symlinks
    for entry in sorted(os.listdir(src)):
        if entry in ("places", "index.theme", ".icon-theme.cache") or entry.startswith("."):
            continue
        expected.add(entry)
        make_symlink(os.path.join(src, entry), os.path.join(dest, entry), src, dest)

    # 3. places directory structure and non-folder symlinks
    src_places = os.path.join(src, "places")
    dst_places = os.path.join(dest, "places")
    ensure_dir(dst_places)
    expected.add("places")

    bodies = load_bodies(bodies_path) if bodies_path else {}
    recolor_items = []

    for sname in sorted(os.listdir(src_places)):
        sdir = os.path.join(src_places, sname)
        ddir = os.path.join(dst_places, sname)

        if os.path.islink(sdir):
            expected.add(f"places/{sname}")
            link = os.readlink(sdir)
            # A pack that switched a size from a real directory to a symlink
            # must not leave the old directory shadowing the new link.
            if os.path.isdir(ddir) and not os.path.islink(ddir):
                shutil.rmtree(ddir)
            if os.path.islink(ddir):
                if os.readlink(ddir) != link:
                    os.unlink(ddir)
                    os.symlink(link, ddir)
            elif not os.path.lexists(ddir):
                os.symlink(link, ddir)
            continue
        if not os.path.isdir(sdir):
            continue

        expected.add(f"places/{sname}")
        ensure_dir(ddir)

        for fname in os.listdir(sdir):
            fsrc = os.path.join(sdir, fname)
            fdst = os.path.join(ddir, fname)
            expected.add(f"places/{sname}/{fname}")

            # Never treat symlinks as files to recolour; replicate the symlink instead
            if os.path.islink(fsrc):
                make_symlink(fsrc, fdst, src, dest)
                continue

            # Folder SVGs include regular folder*.svg and user-desktop.svg / user-home.svg
            is_folder_svg = (
                sname != "symbolic"
                and "symbolic" not in fname
                and (fname.startswith("folder") or fname in ("user-desktop.svg", "user-home.svg"))
                and fname.endswith(".svg")
                and os.path.isfile(fsrc)
            )

            if not is_folder_svg:
                make_symlink(fsrc, fdst, src, dest)
            else:
                # If fdst was previously a symlink, unlink it so atomic replace writes a real file
                if os.path.islink(fdst):
                    try:
                        os.unlink(fdst)
                    except OSError:
                        pass
                recolor_items.append((fsrc, fdst, f"{sname}/{fname}"))

    # 4. Atomic recolouring of all folder SVGs
    for fsrc, fdst, key in recolor_items:
        with open(fsrc, "r", encoding="utf-8", errors="replace", newline="") as fh:
            text = fh.read()
        body = bodies.get(key) or bodies.get(key.replace("user-", "folder-"))
        atomic_write(fdst, recolor(text, target, body))

    # 5. Drop entries the pack no longer ships (removed sizes, renamed icons).
    removed = prune_stale(dest, expected)
    if removed:
        plural = "entry" if removed == 1 else "entries"
        print(f"recolor.py: pruned {removed} stale {plural}", file=sys.stderr)

    # 6. Touch directory timestamps to notify inotify / mtime watchers
    now = time.time()
    try:
        os.utime(dst_places, (now, now))
        os.utime(dest, (now, now))
    except OSError:
        pass


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    commands = parser.add_subparsers(dest="command", required=True)
    sync = commands.add_parser("sync", help="build or refresh the derived theme")
    sync.add_argument("target", help="six-digit hex colour, with or without '#'")
    sync.add_argument("src", help="source icon pack")
    sync.add_argument("dest", help="derived theme directory")
    sync.add_argument("--bodies", help="body table written by gen_bodies.py")
    args = parser.parse_args(argv)
    sync_theme(args.src, args.dest, args.target, args.bodies)


if __name__ == "__main__":
    main()
